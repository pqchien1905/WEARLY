const { chromium } = require('../.tools/browser/node_modules/playwright');
const fs = require('fs');
const path = require('path');
const out = path.resolve(__dirname, '../docs/qa');
const results = [], errors = [], external = [];
(async () => {
  const browser = await chromium.launch({executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true});
  const page = await browser.newPage({viewport: {width: 1440, height: 1000}});
  page.setDefaultTimeout(12000);
  page.on('pageerror', e => errors.push(e.message));
  page.on('request', r => {if (!r.url().startsWith('http://127.0.0.1:4173') && !r.url().startsWith('blob:') && !r.url().startsWith('data:')) external.push({url:r.url(),method:r.method()});});
  const button = name => page.getByRole('button', {name, exact:true});
  const snap = () => page.locator('body').ariaSnapshot();
  const check = async (label, expected) => {const s=await snap(); if(!s.includes(expected)) throw new Error(`${label}: missing ${expected}\n${s}`); results.push(label); console.log('PASS '+label);};
  const route = async url => {await page.evaluate(url => location.hash=url,url); await page.waitForTimeout(700);};
  try {
    await page.goto('http://127.0.0.1:4173/#/products/nep-1');
    await page.waitForTimeout(2000);
    await page.evaluate(()=>document.querySelector('flt-semantics-placeholder')?.click());
    await button('M').click();
    await button('Lưu yêu thích').click();
    await button('Thêm vào giỏ').click();
    await page.waitForTimeout(700);
    fs.writeFileSync(path.join(out,'browser-snapshot.txt'),await snap());
    await check('Add selected SKU to cart', '490.000');
    // Escape dismisses the cart drawer using the real browser keyboard.
    await page.keyboard.press('Escape');
    await route('/checkout');
    for (const [label,value] of [['Họ và tên','Nguyễn An'],['Email','an@example.com'],['Số điện thoại','0901234567'],['Địa chỉ đầy đủ','12 Nguyễn Huệ, Quận 1, TP.HCM']]) await page.getByRole('textbox',{name:label,exact:true}).fill(value);
    await page.getByRole('checkbox',{name:/Tôi hiểu đây/}).check();
    await button('Tạo đơn hàng demo').click();
    await page.waitForTimeout(1200);
    await check('Checkout creates order', 'WRL-0001');
    await page.screenshot({path:path.join(out,'screenshots/checkout-success-1440.png')});
    await route('/wishlist');
    await check('Wishlist survives route changes', 'Áo cotton không tay Essential');
    await route('/admin/orders');
    await check('Admin receives session order', 'WRL-0001');
    await page.screenshot({path:path.join(out,'screenshots/admin-orders-1440.png')});
    await route('/ai-stylist');
    fs.writeFileSync(path.join(out,'browser-snapshot.txt'),await snap());
    await page.getByRole('textbox').first().fill('Tôi cần đồ tối giản đi làm');
    await button('Gửi yêu cầu').click();
    await page.waitForTimeout(1500);
    await check('Stylist recommends catalog products', 'Tổng gợi ý:');
    await page.screenshot({path:path.join(out,'screenshots/stylist-result-1440.png')});
    await route('/virtual-try-on?product=nep-1');
    const chooser=page.waitForEvent('filechooser');
    await button('Chọn ảnh từ thiết bị').click();
    await (await chooser).setFiles(path.resolve(__dirname,'../frontend/assets/images/shirt.jpg'));
    await page.waitForTimeout(500);
    fs.writeFileSync(path.join(out,'browser-snapshot.txt'),await snap());
    await button('Chọn màu và size').click();
    await page.getByRole('menuitem',{name:'Trắng / M',exact:true}).click();
    await page.getByRole('checkbox',{name:/Tôi có quyền/}).click();
    await page.waitForTimeout(300);
    await button('Tạo bản thử đồ demo').click();
    await page.waitForTimeout(2200);
    await check('Try-On completes with explicit demo disclosure', 'không phải kết quả AI thực tế');
    await button('Trở lại chọn size & mua').scrollIntoViewIfNeeded();
    await page.waitForTimeout(300);
    await page.screenshot({path:path.join(out,'screenshots/tryon-result-1440.png')});
    await button('Xóa ảnh & kết quả').click();
    await check('Private photo cleared', 'Chọn ảnh từ thiết bị');
    await route('/shop?category=dam&size=M');
    await check('Catalog deep link restores filters', 'Váy & đầm');
    await route('/shop?category=ao');
    await page.goBack();
    await page.waitForTimeout(700);
    if(!page.url().includes('category=dam')) throw Error('Browser back lost query');
    results.push('Browser back restores catalog query');
    await route('/admin');
    await page.screenshot({path:path.join(out,'screenshots/admin-dashboard-1440.png')});
  } catch(e) {
    errors.push(e.stack);
    fs.writeFileSync(path.join(out,'browser-failure-snapshot.txt'),await snap());
    await page.screenshot({path:path.join(out,'screenshots/browser-failure.png')});
    process.exitCode=1;
  } finally {
    fs.writeFileSync(path.join(out,'browser-flow.json'),JSON.stringify({results,errors,externalRequests:external},null,2));
    console.log(JSON.stringify({results,errors,externalRequests:external},null,2));
    await browser.close();
  }
})();
